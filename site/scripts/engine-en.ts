// The English of the texts the café engine draws (sign, door pill, receipts, the admin's shouts…), for the site's
// shim (src/hero/engine-i18n.ts). The keys are found with the shared scanner in the engine files the site bundles;
// the English comes from the product's catalogs. Never import those catalogs into the browser (420 KB together).
//   node site/scripts/engine-en.ts      (also prebuild / pretest)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { keysIn } from '../../scripts/i18n/scan.mjs';
import { readCatalog, root } from '../../scripts/i18n/catalog.mjs';

/** What the site bundles from the engine and calls tr() (validate.ts too, but its texts never show on the site). */
export const ENGINE_FILES = [
  'web/src/features/cafe/map.ts',
  'web/src/features/cafe/sim.ts',
  'web/src/features/cafe/render.ts',
  'web/src/features/cafe/money.ts',
  'server/src/characters/core/builtin.ts',
];
export const OUT = path.join(root, 'site/src/hero/engine-en.generated.ts');

export function engineEnglish(): { entries: Record<string, string>; missing: string[] } {
  const web = readCatalog({ catalog: 'web/src/i18n/en.ts', export: 'EN_WEB' });
  const server = readCatalog({ catalog: 'server/src/i18n/en.ts', export: 'EN_SERVER' });
  const keys = new Set<string>();
  for (const rel of ENGINE_FILES) {
    const file = path.join(root, rel);
    for (const k of keysIn(file, fs.readFileSync(file, 'utf8')).keys) keys.add(k.key);
  }
  const entries: Record<string, string> = {};
  const missing: string[] = [];
  for (const k of [...keys].sort()) {
    const en = web[k] ?? server[k];
    if (en === undefined) missing.push(k); else entries[k] = en;
  }
  return { entries, missing };
}

export function generated(entries: Record<string, string>): string {
  const body = Object.keys(entries).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(entries[k])},`).join('\n');
  return `// GENERATED by site/scripts/engine-en.ts from the product's catalogs — do not edit.\nexport const ENGINE_EN: Record<string, string> = {\n${body}\n};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { entries, missing } = engineEnglish();
  if (missing.length) {
    console.error(`engine-en: no English for ${missing.length} text(s):\n${missing.map((k) => `  ${k}`).join('\n')}`);
    process.exit(1);
  }
  const text = generated(entries);
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) fs.writeFileSync(OUT, text);
  console.log(`engine-en: ${Object.keys(entries).length} texts`);
}
